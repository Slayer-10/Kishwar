/**
 * CLEANUP DRY-RUN INSPECTION
 * Reads current record counts and identifies admin identity.
 * No writes, no deletes, no schema changes.
 */
import { prisma } from '../lib/prisma';

const ADMIN_EMAIL = 'elbusnape@gmail.com';

async function main() {
  console.log('\n========================================');
  console.log('  DATABASE DRY-RUN INSPECTION REPORT');
  console.log('========================================\n');

  // 1. Identify admin
  const admin = await prisma.user.findUnique({
    where: { email: ADMIN_EMAIL },
    select: { id: true, email: true, role: true, isActive: true },
  });

  if (!admin) {
    console.error('❌ FATAL: Admin account not found. Aborting.');
    process.exit(1);
  }

  console.log('✅ Admin account identified:');
  console.log(`   ID:     ${admin.id}`);
  console.log(`   Email:  ${admin.email}`);
  console.log(`   Role:   ${admin.role}`);
  console.log(`   Active: ${admin.isActive}`);

  if (admin.role !== 'SUPER_ADMIN') {
    console.warn('⚠️  Warning: Admin role is not SUPER_ADMIN — it is:', admin.role);
  }

  // 2. All users
  const allUsers = await prisma.user.findMany({ select: { id: true, email: true, role: true } });
  console.log(`\n--- Users (${allUsers.length} total) ---`);
  for (const u of allUsers) {
    const marker = u.id === admin.id ? ' ← ADMIN (will be preserved)' : '';
    console.log(`  [${u.role}] ${u.email}${marker}`);
  }

  const nonAdminUsers = allUsers.filter(u => u.id !== admin.id);
  console.log(`  → ${nonAdminUsers.length} non-admin user(s) will be targeted for removal`);

  // 3. Record counts
  const counts = {
    NotificationLog:     await prisma.notificationLog.count(),
    Announcement:        await prisma.announcement.count(),
    AuditLog:            await prisma.auditLog.count(),
    Ticket:              await prisma.ticket.count(),
    RegistrationEvidence:await prisma.registrationEvidence.count(),
    Payment:             await prisma.payment.count(),
    CampusPayment:       await prisma.campusPayment.count(),
    Invoice:             await prisma.invoice.count(),
    CollectiveInvoiceItem: await prisma.collectiveInvoiceItem.count(),
    CollectiveInvoice:   await prisma.collectiveInvoice.count(),
    Registration:        await prisma.registration.count(),
    TeamMember:          await prisma.teamMember.count(),
    Team:                await prisma.team.count(),
    AmbassadorRequest:   await prisma.ambassadorRequest.count(),
    Ambassador:          await prisma.ambassador.count(),
    FDO:                 await prisma.fDO.count(),
    Participant:         await prisma.participant.count(),
    University:          await prisma.university.count(),
    Event:               await prisma.event.count(),
    DiscountTier:        await prisma.discountTier.count(),
    User:                await prisma.user.count(),
  };

  console.log('\n--- Record counts by table ---');
  for (const [table, count] of Object.entries(counts)) {
    console.log(`  ${table.padEnd(24)} ${count}`);
  }

  // 4. Admin audit-log count (will NOT be deleted since admin is preserved)
  const adminAuditCount = await prisma.auditLog.count({
    where: { userId: admin.id },
  });
  console.log(`\n  AuditLogs belonging to admin: ${adminAuditCount} (will be deleted along with all audit logs)`);

  // 5. Collective invoices referencing admin as generatedBy
  const adminCollectiveInvoices = await prisma.collectiveInvoice.count({
    where: { generatedById: admin.id },
  });
  console.log(`  CollectiveInvoices generated by admin: ${adminCollectiveInvoices}`);

  // 6. Registrations confirmed by admin
  const adminConfirmedRegs = await prisma.registration.count({
    where: { paymentConfirmedById: admin.id },
  });
  console.log(`  Registrations payment-confirmed by admin: ${adminConfirmedRegs}`);

  // 7. Registration evidence uploaded/reviewed by admin
  const adminUploadedEvidence = await prisma.registrationEvidence.count({
    where: { uploadedByUserId: admin.id },
  });
  const adminReviewedEvidence = await prisma.registrationEvidence.count({
    where: { reviewedByUserId: admin.id },
  });
  console.log(`  RegistrationEvidence uploaded by admin:  ${adminUploadedEvidence}`);
  console.log(`  RegistrationEvidence reviewed by admin:  ${adminReviewedEvidence}`);

  // 8. Storage paths to inspect
  const evidencePaths = await prisma.registrationEvidence.findMany({
    select: { storagePath: true, type: true },
  });
  console.log(`\n--- Supabase Storage objects (from RegistrationEvidence) ---`);
  if (evidencePaths.length === 0) {
    console.log('  None found.');
  } else {
    for (const e of evidencePaths) {
      console.log(`  [${e.type}] ${e.storagePath}`);
    }
  }

  const campusPaymentPaths = await prisma.campusPayment.findMany({
    select: { proofUrl: true },
  });
  console.log(`\n--- Supabase Storage objects (from CampusPayment proofUrl) ---`);
  if (campusPaymentPaths.length === 0) {
    console.log('  None found.');
  } else {
    for (const p of campusPaymentPaths) {
      console.log(`  ${p.proofUrl}`);
    }
  }

  // 9. Database target hint (no secrets)
  const dbUrl = process.env.DATABASE_URL ?? '';
  const dbHint = dbUrl.replace(/:[^:@]*@/, ':***@'); // mask password only
  console.log('\n--- Database target (password masked) ---');
  console.log(`  ${dbHint}`);

  console.log('\n========================================');
  console.log('  DRY-RUN COMPLETE. No changes made.');
  console.log('========================================\n');
}

main()
  .catch((e) => {
    console.error('Dry-run inspection failed:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
