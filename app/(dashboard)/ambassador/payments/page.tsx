import React from 'react';
import { prisma } from '@/lib/prisma';
import { getCurrentUser } from '@/lib/auth';
import { redirect } from 'next/navigation';
import { submitCollectiveInvoicePaymentAction } from '@/app/(dashboard)/ambassador/actions';
import { StatusBadge } from '@/components/ui/StatusBadge';
import { Button } from '@/components/ui/Button';

export const dynamic = 'force-dynamic';

export default async function AmbassadorPaymentsPage({
  searchParams,
}: {
  searchParams: { error?: string; submitted?: string };
}) {
  const user = await getCurrentUser();

  if (!user || user.role !== 'AMBASSADOR' || !user.ambassador) {
    redirect('/login');
  }

  const ambassador = await prisma.ambassador.findUnique({
    where: { id: user.ambassador.id },
    include: { university: true },
  });

  if (!ambassador) {
    redirect('/login');
  }

  // Query only this Ambassador's collective invoices, with their line items
  // and linked payment submission (if any).
  const invoices = await prisma.collectiveInvoice.findMany({
    where: { ambassadorId: ambassador.id },
    include: {
      paymentSubmission: true,
      items: {
        include: {
          registration: {
            include: {
              event: { select: { name: true } },
              participant: { select: { fullName: true, email: true } },
              team: { select: { name: true } },
            },
          },
        },
        orderBy: { createdAt: 'asc' },
      },
    },
    orderBy: { createdAt: 'desc' },
  });

  const currency = (value: number | string | { toString(): string }) =>
    `PKR ${Number(value).toLocaleString('en-PK', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })}`;

  const submissionStatusLabel = (status: string | undefined | null) => {
    if (!status) return null;
    if (status === 'SUBMITTED') return 'Awaiting Admin review';
    if (status === 'VERIFIED') return 'Verified — paid';
    if (status === 'REJECTED') return 'Rejected — please resubmit';
    return status;
  };

  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-col">
        <h1
          style={{
            fontFamily: 'var(--font-heading)',
            fontSize: 'var(--fs-title1)',
            lineHeight: 'var(--lh-title1)',
            color: 'var(--color-text)',
          }}
          className="font-bold uppercase tracking-tight"
        >
          Collective Invoices
        </h1>
        <div
          className="mt-2 h-[4px] w-[56px] rounded-[2px]"
          style={{ backgroundColor: 'var(--color-primary)' }}
        />
        <p className="mt-2 text-sm text-[var(--color-text-muted)]">
          Collective invoices are generated by Admin and cover all eligible registrations
          attributed to your Ambassador account.
        </p>
      </div>

      {searchParams.error && (
        <div
          role="alert"
          className="p-4 rounded-[var(--radius-md)] bg-red-50 border border-red-200 text-red-700 text-sm font-medium"
        >
          {searchParams.error}
        </div>
      )}

      {searchParams.submitted === '1' && (
        <div
          role="status"
          className="p-4 rounded-[var(--radius-md)] bg-green-50 border border-green-200 text-green-800 text-sm font-medium"
        >
          ✓ Payment proof submitted. Admin will review it shortly.
        </div>
      )}

      {invoices.length === 0 ? (
        <div className="p-8 rounded-[var(--radius-lg)] bg-[var(--color-surface)] shadow-[var(--shadow-card)] text-center">
          <p className="text-sm text-[var(--color-text-muted)]">
            No collective invoices have been generated for your account yet.
          </p>
        </div>
      ) : (
        <div className="flex flex-col gap-6">
          {invoices.map((invoice) => {
            const proof = invoice.paymentSubmission;
            const isPaid = invoice.status === 'PAID';
            const proofStatus = proof?.verificationStatus ?? null;
            const canSubmit =
              !isPaid &&
              proofStatus !== 'SUBMITTED' &&
              proofStatus !== 'VERIFIED';

            return (
              <section
                key={invoice.id}
                className={`rounded-[var(--radius-lg)] bg-[var(--color-surface)] shadow-[var(--shadow-card)] border-t-4 ${
                  isPaid
                    ? 'border-t-emerald-500'
                    : proofStatus === 'SUBMITTED'
                    ? 'border-t-amber-400'
                    : proofStatus === 'REJECTED'
                    ? 'border-t-red-400'
                    : 'border-t-[var(--color-primary)]'
                } overflow-hidden`}
              >
                {/* Invoice Header */}
                <div className="p-5 flex flex-wrap items-start justify-between gap-3 border-b border-[var(--color-divider)]">
                  <div>
                    <p className="font-bold text-[var(--color-primary)] text-base">
                      {invoice.invoiceNumber}
                    </p>
                    <p className="text-xs text-[var(--color-text-muted)] mt-0.5">
                      Generated {new Date(invoice.createdAt).toLocaleString()}
                    </p>
                  </div>
                  <StatusBadge status={invoice.status} />
                </div>

                {/* Financials */}
                <div className="px-5 py-4 grid grid-cols-2 sm:grid-cols-4 gap-3 text-sm bg-[var(--color-background)] border-b border-[var(--color-divider)]">
                  <div>
                    <p className="text-xs text-[var(--color-text-muted)] font-medium">Subtotal</p>
                    <p className="font-semibold text-[var(--color-text)]">{currency(invoice.subtotal)}</p>
                  </div>
                  <div>
                    <p className="text-xs text-[var(--color-text-muted)] font-medium">Discount</p>
                    <p className="font-semibold text-green-700">
                      {Number(invoice.discountPercent)}% ({currency(invoice.discountAmount)})
                    </p>
                  </div>
                  <div className="col-span-2">
                    <p className="text-xs text-[var(--color-text-muted)] font-medium">Total Due</p>
                    <p className="font-bold text-[var(--color-primary)] text-lg">{currency(invoice.totalAmount)}</p>
                  </div>
                </div>

                {/* Line Items */}
                <div className="p-5 border-b border-[var(--color-divider)]">
                  <h3 className="text-xs font-bold uppercase text-[var(--color-text-muted)] mb-3 tracking-wide">
                    Registrations ({invoice.items.length})
                  </h3>
                  <ul className="flex flex-col divide-y divide-[var(--color-divider)] text-sm">
                    {invoice.items.map((item) => {
                      const reg = item.registration;
                      const name =
                        reg.participant?.fullName ?? reg.team?.name ?? 'Unnamed';
                      const email = reg.participant?.email ?? '';
                      return (
                        <li key={item.id} className="py-2.5 grid grid-cols-2 sm:grid-cols-4 gap-2">
                          <div className="sm:col-span-2">
                            <p className="font-semibold text-[var(--color-text)]">{name}</p>
                            {email && (
                              <p className="text-xs text-[var(--color-text-muted)]">{email}</p>
                            )}
                            <p className="text-xs text-[var(--color-text-muted)]">{reg.event.name}</p>
                          </div>
                          <div className="text-right sm:text-left">
                            <p className="text-xs text-[var(--color-text-muted)]">Base</p>
                            <p className="font-medium">{currency(item.baseAmount)}</p>
                          </div>
                          <div className="text-right">
                            <p className="text-xs text-[var(--color-text-muted)]">Final</p>
                            <p className="font-bold text-[var(--color-primary)]">{currency(item.finalAmount)}</p>
                          </div>
                        </li>
                      );
                    })}
                  </ul>
                </div>

                {/* Payment Submission Status */}
                <div className="p-5">
                  {isPaid ? (
                    <div className="flex items-center gap-2">
                      <span className="text-sm font-bold text-emerald-700">✓ Payment confirmed by Admin</span>
                    </div>
                  ) : proofStatus === 'SUBMITTED' ? (
                    <div className="flex flex-col gap-2">
                      <div className="flex items-center gap-2">
                        <StatusBadge status="SUBMITTED" />
                        <span className="text-sm font-semibold text-amber-800">
                          {submissionStatusLabel(proofStatus)}
                        </span>
                      </div>
                      <p className="text-xs text-[var(--color-text-muted)]">
                        Method: {proof!.method}
                        {proof!.referenceNumber ? ` · Ref: ${proof!.referenceNumber}` : ''}
                        {' · '}
                        Submitted {new Date(proof!.createdAt).toLocaleString()}
                      </p>
                      {proof!.proofUrl && (
                        <a
                          href={proof!.proofUrl}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="text-xs font-semibold text-[var(--color-primary)] hover:underline"
                        >
                          View submitted proof ↗
                        </a>
                      )}
                    </div>
                  ) : proofStatus === 'REJECTED' ? (
                    <div className="flex flex-col gap-3">
                      <div className="flex items-center gap-2">
                        <StatusBadge status="REJECTED" />
                        <span className="text-sm font-semibold text-red-700">
                          Proof rejected — resubmit below
                        </span>
                      </div>
                      <p className="text-xs text-[var(--color-text-muted)]">
                        Previous method: {proof!.method}
                        {proof!.referenceNumber ? ` · Ref: ${proof!.referenceNumber}` : ''}
                      </p>
                    </div>
                  ) : (
                    <p className="text-sm text-[var(--color-text-muted)]">
                      No payment proof submitted yet.
                    </p>
                  )}

                  {/* Payment submission form — shown when proof not yet submitted or was rejected */}
                  {canSubmit && (
                    <form
                      action={submitCollectiveInvoicePaymentAction}
                      className="mt-4 flex flex-col gap-4 pt-4 border-t border-[var(--color-divider)]"
                    >
                      <input type="hidden" name="collectiveInvoiceId" value={invoice.id} />

                      <h3 className="text-sm font-bold uppercase text-[var(--color-text)]">
                        {proofStatus === 'REJECTED' ? 'Resubmit Payment Proof' : 'Submit Payment Proof'}
                      </h3>

                      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                        <div>
                          <label className="form-label">Payment Method *</label>
                          <input
                            name="method"
                            type="text"
                            placeholder="e.g. JazzCash / EasyPaisa / Bank Transfer"
                            required
                            className="form-input"
                          />
                        </div>
                        <div>
                          <label className="form-label">Reference Number</label>
                          <input
                            name="referenceNumber"
                            type="text"
                            placeholder="Transaction ID / Ref # (optional)"
                            className="form-input"
                          />
                        </div>
                        <div>
                          <label className="form-label">Payment Screenshot URL *</label>
                          <input
                            name="proofUrl"
                            type="url"
                            placeholder="https://drive.google.com/..."
                            required
                            className="form-input"
                          />
                          <p className="mt-1 text-xs text-[var(--color-text-muted)]">
                            Paste a publicly accessible screenshot link (Google Drive, Dropbox, etc.).
                          </p>
                        </div>
                      </div>

                      <Button type="submit" variant="primary" className="self-start mt-1">
                        Submit Payment Proof for {currency(invoice.totalAmount)}
                      </Button>
                    </form>
                  )}
                </div>
              </section>
            );
          })}
        </div>
      )}
    </div>
  );
}
